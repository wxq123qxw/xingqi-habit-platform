/**
 * 兜底通用文案（spec §4.1.3）
 * 5 种定制风格统一回退到这 3 条模板，从 3 条中随机选一
 */
export const FALLBACK_TEMPLATES: string[] = [
  '{habitName} 别忘了哦，今天也要加油！',
  '坚持就是胜利 —— {habitName} 打卡时间到',
  '再忙也要照顾好自己 —— {habitName}',
];

/** 兜底文案插入 habitName */
export function fillFallbackTemplate(
  template: string,
  habitName: string
): string {
  return template.replace(/\{habitName\}/g, habitName);
}

/** 验证字符串是否符合 spec 的文案格式（5-15 汉字 + 不含特殊分隔符） */
export function isValidReminderText(text: string): boolean {
  // 只算汉字（含中文标点不算）
  const hanMatches = text.match(/[\u4e00-\u9fa5]/g) ?? [];
  return hanMatches.length >= 5 && hanMatches.length <= 15;
}